"""Generate research/results_v2.md FROM the JSON/CSV outputs in results/v2 (no hand-typed numbers).
Run after all other v2 scripts: python scripts/v2/make_results_v2.py"""
from __future__ import annotations

import json
import re
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
T = ROOT / "results" / "v2" / "tables"
MB = ROOT / "results" / "v2" / "manifoldbt"
SEEN = "seen period (v1 reported it)"
HASH = "b14b0cc95d53"


def J(n, d=T):
    return json.load(open(d / n))


def ci(s, lo, hi, p=2):
    return f"{s:.{p}f} [{lo:.{p}f}, {hi:.{p}f}]"


def md(df: pd.DataFrame) -> str:
    cols = list(df.columns)
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        out.append("| " + " | ".join("" if (isinstance(v, float) and pd.isna(v)) else str(v) for v in r) + " |")
    return "\n".join(out)


def verdict(b: bool) -> str:
    return "SUPPORTED" if b else "NOT SUPPORTED"


def main():
    h = J("h1_h2_trading.json")
    ov = J("overfit_audit.json")
    d2, d2t, d2d = J("d2_allocation.json"), pd.read_csv(T / "d2_allocation.csv"), pd.read_csv(T / "d2_allocation_diff.csv")
    d3 = pd.read_csv(T / "d3_crisis_corr.csv")
    e1 = J("e1_hmm.json")
    d46 = J("d4_d6.json")
    sens = J("h1_sensitivity_lowrate.json")
    d8 = pd.read_csv(T / "d8_rate_grid_2001_2012.csv")
    ex, cap, sp = pd.read_csv(T / "execution.csv"), pd.read_csv(T / "capacity.csv"), pd.read_csv(T / "seen_period.csv")
    fwd_path = ROOT / "results" / "v2" / "forward" / "forward.csv"
    fwd = pd.read_csv(fwd_path) if fwd_path.exists() else pd.DataFrame(columns=["date", "book", "net_return"])
    n_fwd = fwd["date"].nunique()
    parity = (ROOT.parent / "qengine" / "PARITY.md").read_text(encoding="utf-8")
    pm = re.search(r"corr\(run_weights, mbt\) = ([\d.]+); corr\(run_contracts, mbt\) = ([\d.]+)", parity)
    ps = re.search(r"Sharpe: mbt ([\d.\-]+), run_weights ([\d.\-]+), run_contracts ([\d.\-]+)", parity)

    H1, H2, H3 = h["H1"]["supported"], h["H2"]["supported"], ov["H3"]["supported"]
    ns, g, ac = h["net_sharpe"], h["gross_sharpe"], h["annual_cost"]
    l1 = h["lag1_secondary"]
    sl = sens["lag2"]
    sc = pd.DataFrame(sens["chosen"])
    o = []
    A = o.append
    A("# P8 v2 results: Seven Engines, cost-aware upgrade")
    A("")
    A(f"Generated by `scripts/v2/make_results_v2.py` from `results/v2/tables/*`. Pre-registration v2 hash `{HASH}` (never edited). "
      "Research artifact, not investment advice, not a live-trading instruction.")
    A("")
    A("**Timing.** Every signal is computed at the close of day t from data up to and including t. v1 trades at that close "
      "(`lag=1`); v2 reports the realistic `lag=2` (trade at the next close) as the primary case. Choices used 2001-2017 data only; "
      "the H1 walk-forward is out of sample inside that period (2009-2017).")
    A("")
    A("## Bottom line")
    A("")
    A(f"- H1 (partial adjustment cuts cost at least 40% and keeps gross Sharpe at least 80% of v1): **{verdict(H1)}** at lag 2. "
      f"Cost {ac['h1']:.2%}/yr vs {ac['v1_buffer']:.2%}/yr ({ac['reduction']:.1%} lower); gross Sharpe {g['h1']:.2f} vs {g['v1_buffer']:.2f}.")
    A(f"- H2 (H1 net Sharpe beats v1, difference CI excludes 0): **{verdict(H2)}** at lag 2. H1 {ci(*ns['h1'])} vs v1 {ci(*ns['v1_buffer'])}; "
      f"difference {ci(*ns['diff_h1_minus_v1'])}. The H1 net Sharpe interval itself still includes zero.")
    A(f"- H3 (v1 is not an overfit pick: PBO < 0.5 and deflated Sharpe > 0.90): **{verdict(H3)}**. PBO {ov['pbo']:.3f} passes; "
      f"deflated Sharpe {ov['v1_deflated_sharpe']:.4f} fails.")
    A(f"- **Lag-2 caveat.** At lag 1 (secondary) the gross-Sharpe ratio is {l1['h1_gross'] / l1['v1_gross']:.2f} "
      f"(H1 {l1['h1_gross']:.2f} vs v1 {l1['v1_gross']:.2f}), which would FAIL H1's gross leg. H1 is supported only at the pre-registered lag 2.")
    A("- **Grid-edge caveat.** The pre-registered rate grid started at 0.05 and the walk-forward chose 0.05 in every fold. The sensitivity below "
      f"(not in the prereg) extends the grid down to 0.01: H1 supported = {sl['H1_supported']}, H2 supported = {sl['H2_supported']} at lag 2, so the conclusion does not change.")
    A("- E1 (HMM style tilt, exploratory): no value.")
    v1r = ex[(ex.book == "v1 blend") & (ex.period == "2001-2017") & (ex.run == "v1 costs lag2")].iloc[0]
    A(f"- v1 blend lag 2, 2001-2017: Sharpe {ci(v1r.net_sharpe, v1r.ci95_lo, v1r.ci95_hi)}; "
      "the H1 blend is better but its interval also includes zero. No book has a demonstrated edge in 2001-2017.")
    A("")
    A("## Hypotheses")
    A("")
    hyp = pd.DataFrame([
        ["H1 trading cost", "cost cut >= 40% and gross >= 80% of v1", f"cut {ac['reduction']:.1%}; gross ratio {g['ratio']:.2f}", verdict(H1)],
        ["H2 net Sharpe", "H1 net > v1 net, diff CI excludes 0", f"diff {ci(*ns['diff_h1_minus_v1'])}", verdict(H2)],
        ["H3 overfitting", "PBO < 0.5 and DSR > 0.90", f"PBO {ov['pbo']:.3f}; DSR {ov['v1_deflated_sharpe']:.4f}", verdict(H3)],
    ], columns=["hypothesis", "rule (prereg)", "result", "verdict"])
    A(md(hyp))
    A("")
    A("### H1 and H2 detail (walk-forward OOS 2009-2017, lag 2, 2319 days)")
    A("")
    A(md(pd.DataFrame(h["chosen"])[["fold", "params", "train_sharpe", "test_sharpe"]].round(3)))
    A("")
    A(f"- Turnover per year: H1 {h['turnover_per_year']['h1']:.1f} vs v1 buffer {h['turnover_per_year']['v1_buffer']:.1f}. "
      f"Rebalance days: H1 {h['rebalance_days']['h1']}, v1 buffer {h['rebalance_days']['v1_buffer']} of {h['n_oos_days']}.")
    A(f"- Lag 1 (secondary): H1 net {ci(*l1['h1_net_sharpe'])} vs v1 {ci(*l1['v1_net_sharpe'])}.")
    A(f"- D7 cost-scaled no-trade band (not part of H1): net {ci(*ns['cost_band_D7'])}, cost {ac['cost_band_D7']:.2%}/yr: no help.")
    A("")
    A("### SENSITIVITY (not in the prereg): extended rate grid for H1")
    A("")
    A("The prereg grid was rate in {0.05, 0.1, 0.2, 0.35, 0.5, 1.0} x cost-scaled in {False, True}. The walk-forward chose the lowest rate in every fold, "
      "so this run adds 0.01, 0.02, 0.03 (script `scripts/v2/h1_sensitivity.py`). It does not replace the pre-registered verdict.")
    A("")
    A(md(sc[["fold", "params", "train_sharpe", "test_sharpe"]].round(3)))
    A("")
    s1 = sens["lag1"]
    cmp_ = pd.DataFrame([
        ["lag 2", "pre-registered grid", f"{ac['reduction']:.1%}", f"{g['ratio']:.2f}", ci(*ns['h1']), ci(*ns['diff_h1_minus_v1']), verdict(H1), verdict(H2)],
        ["lag 2", "extended grid (sensitivity)", f"{sl['annual_cost']['reduction']:.1%}", f"{sl['gross_sharpe']['ratio']:.2f}", ci(*sl['net_sharpe']['h1']), ci(*sl['net_sharpe']['diff_h1_minus_v1']), verdict(sl['H1_supported']), verdict(sl['H2_supported'])],
        ["lag 1", "extended grid (sensitivity)", f"{s1['annual_cost']['reduction']:.1%}", f"{s1['gross_sharpe']['ratio']:.2f}", ci(*s1['net_sharpe']['h1']), ci(*s1['net_sharpe']['diff_h1_minus_v1']), verdict(s1['H1_supported']), verdict(s1['H2_supported'])],
    ], columns=["lag", "grid", "cost cut", "gross ratio", "H1 net Sharpe [CI]", "net diff vs v1 [CI]", "H1", "H2"])
    A(md(cmp_))
    A("")
    picks = sorted(set(sc["params"]))
    A(f"Chosen settings with the extended grid: {', '.join(picks)}. The new low rates (0.01-0.03) were never chosen, so the grid edge was not a binding constraint. "
      "Selection uses the walk-forward plateau rule, so adding cells can move a fold's pick. "
      "Conclusion: H1 and H2 stay supported at lag 2 and fail at lag 1 for the same reason as before. Development-period (2001-2012) results by rate are in "
      "`results/v2/tables/h1_sensitivity_rate_grid_2001_2012.csv`; no choice was made from them.")
    A("")
    A("### H3 detail")
    A("")
    A(f"- Window {ov['window'][0]} to {ov['window'][1]} ({ov['n_days']} days; value needs 5 years of history). {ov['n_trials']} configs "
      "(8 books x 4 buffers x 3 vol windows), v1 timing and costs (lag 1).")
    A(f"- v1 blend Sharpe {ci(ov['v1_blend_ann_sharpe'], *ov['v1_blend_ci95'])}; expected maximum Sharpe of {ov['n_trials']} null trials {ov['expected_max_sharpe_annualised']:.2f}; "
      f"PSR vs 0 {ov['v1_psr_vs_0']:.3f}; deflated Sharpe {ov['v1_deflated_sharpe']:.4f}. Best in-sample config `{ov['best_in_sample']}` at {ov['best_in_sample_ann_sharpe']:.2f}. "
      f"{ov['n_configs_sharpe_gt_0']} of {ov['n_trials']} configs have Sharpe > 0.")
    cp = ov["cpcv"]
    A(f"- CPCV ({cp['n_splits']} splits, {cp['n_groups']} groups, embargo {cp['embargo']}d): selection paths {cp['min_path']:.2f} to {cp['max_path']:.2f}, median {cp['median_path']:.2f}. "
      "These are 2004-2017 data, the choice period, not unseen data.")
    A(f"- PBO {ov['pbo']:.3f} over {ov['pbo_n_combinations']} combinations says selection was stable inside the family, not that the family has an edge. "
      "sr_var was taken literally as the variance of the 96 daily Sharpes (as P7); the configs are correlated, so a smaller effective trial count would raise the DSR, but this was not applied.")
    A("")
    A("## D2 style allocation (2004-2017, lag 2, H1 smoother and v1 buffer)")
    A("")
    t = d2t.copy()
    t["net Sharpe [95% CI]"] = [ci(a, b, c) for a, b, c in zip(t.net_sharpe, t.ci95_lo, t.ci95_hi)]
    t["gross"] = t.gross_sharpe.round(2)
    t["cost/yr"] = t.ann_cost.map("{:.2%}".format)
    t["turnover/yr"] = t.turnover_per_yr.round(1)
    A(md(t[["smoother", "allocation", "net Sharpe [95% CI]", "gross", "cost/yr", "turnover/yr", "n_days"]]))
    A("")
    dd = d2d.copy()
    dd["diff vs v1 equal-risk [CI]"] = [ci(a, b, c) for a, b, c in zip(dd.diff_vs_v1_equal_risk, dd.ci95_lo, dd.ci95_hi)]
    A(md(dd[["smoother", "allocation", "diff vs v1 equal-risk [CI]", "ci_excludes_zero"]]))
    A("")
    A(f"No allocation is distinguishable from equal-risk. Best by net Sharpe on the main smoother: `{d2['best_by_net_sharpe_main_smoother']}` "
      f"(forward-tracker book `alloc_annual_equal`). {d2['note']}.")
    A("")
    A("## D4 and D5: cost budget per style (2001-2017, lag 2, v1 10% buffer)")
    A("")
    A("D4 rule (prereg): annual cost in Sharpe units (annual cost / annual vol of the gross return) at most one third of the style's gross Sharpe. "
      f"D5 (fixed in the prereg, not tuned): a style that fails is restricted to the {d46['n_cheap_markets']} of {d46['n_markets']} markets with cost_bp at or below the universe median "
      f"({d46['cheap_market_cutoff_bp']:.2f} bp); if it still fails it is dropped and the drop is reported. "
      "Gross Sharpe is a 2001-2017 in-sample number, so a restricted style passing here is descriptive, not evidence.")
    A("")
    rows = []
    for s, r in d46["styles"].items():
        for ver, key in (("v1 buffered", "D4"), ("D5 cheap markets only", "D5_restricted_to_cheap")):
            if key not in r:
                continue
            x = r[key]
            rows.append([s, ver, ci(x["gross_sharpe"], *x["gross_ci"]), f"{x['budget_gross_over_3']:.2f}", ci(x["cost_units"], *x["cost_units_ci"]),
                         f"{x['turnover_per_yr']:.0f}", f"{x['net_sharpe']:.2f}", "pass" if x["passes_D4"] else "FAIL"])
    A(md(pd.DataFrame(rows, columns=["style", "version", "gross Sharpe [CI]", "budget (gross/3)", "cost in Sharpe units [CI]", "turnover/yr", "net Sharpe", "D4"])))
    A("")
    fast = all(d46["styles"][s]["outcome"].startswith("still") for s in ("mean_reversion", "liquidity"))
    A("Outcomes: " + "; ".join(f"{s}: {r['outcome']}" for s, r in d46["styles"].items()) + ". "
      "The two fast styles named in D5 (mean reversion, liquidity) "
      + ("both still fail after restriction and are dropped under the rule." if fast else "are reported in the table above.")
      + " Dropping is a report here, not a change to the v1 blend.")
    A("")
    A("## D6 netting")
    A("")
    A("Cost of the blend, whose orders are netted across styles into one book per market, against the sum of the costs of the seven style books traded separately at the same blend weights (lag 2, v1 costs). "
      "Without a band the two books have identical gross P&L (asserted in the script), so the difference is pure cost.")
    A("")
    rows = []
    for k, x in d46["D6"].items():
        rows.append([k, f"{x['netted_cost_per_yr']:.2%}", f"{x['separate_cost_per_yr']:.2%}", ci(x["netting_benefit"], *x["benefit_ci"], p=3),
                     f"{x['netted_cost_sharpe_units']:.2f} vs {x['separate_cost_sharpe_units']:.2f}",
                     f"{x['turnover_netted']:.0f} vs {x['turnover_separate']:.0f}", x["n_days"]])
    A(md(pd.DataFrame(rows, columns=["variant", "netted cost/yr", "separate cost/yr", "netting benefit [CI]",
                                     "cost in Sharpe units (netted vs separate)", "turnover/yr", "days"])))
    A("")
    A("## D8 rate vs half-life (2001-2012 only, lag 2; no rate chosen from it)")
    A("")
    q = d8[d8["rate"].notna()].copy()
    q["net Sharpe"] = q.net_sharpe.round(2)
    q["gross"] = q.gross_sharpe.round(2)
    q["cost/yr"] = q.ann_cost.map("{:.2%}".format)
    q["half-life (days)"] = q.half_life_days.round(1)
    A(md(q[["rate", "cost_scaled", "half-life (days)", "gross", "net Sharpe", "cost/yr"]]))
    A("")
    A("## D3 crisis correlation (monthly net, lag 2)")
    A("")
    c3 = d3[d3.benchmark.isin(["SPY", "managed_futures_avg(AQMIX,ASFYX)"])].copy()
    c3["corr all [CI]"] = [ci(a, b, c) for a, b, c in zip(c3.corr_all, c3.corr_all_lo, c3.corr_all_hi)]
    c3["corr stress [CI]"] = [ci(a, b, c) for a, b, c in zip(c3.corr_stress, c3.corr_stress_lo, c3.corr_stress_hi)]
    c3["joint worst-decile share"] = c3.joint_worst_decile_share.round(3)
    A(md(c3[["period", "book", "benchmark", "n_months_all", "corr all [CI]", "n_months_stress", "corr stress [CI]", "joint worst-decile share"]]))
    A("")
    A(f"Stress samples are 6 to 21 months, so intervals are wide. The 2018-2026 rows are the {SEEN}.")
    A("")
    A("## D1 execution and capacity (2001-2017)")
    A("")
    base = ex[(ex.period == "2001-2017") & ex.run.str.startswith("v1 costs")].copy()
    base["net Sharpe [95% CI]"] = [ci(a, b, c) for a, b, c in zip(base.net_sharpe, base.ci95_lo, base.ci95_hi)]
    base["cost/yr"] = base.ann_cost_total.map("{:.2%}".format)
    base["cost in Sharpe units"] = base.cost_in_sharpe_units.round(2)
    base["turnover/yr"] = base.turnover_per_yr.round(0)
    base["margin/equity"] = base.margin_to_equity.map("{:.0%}".format)
    A(md(base[["book", "run", "net Sharpe [95% CI]", "cost/yr", "cost in Sharpe units", "turnover/yr", "margin/equity"]]))
    A("")
    cont = ex[(ex.period == "2001-2017") & ex.run.str.startswith("integer")].copy()
    cont["net Sharpe [95% CI]"] = [ci(a, b, c) for a, b, c in zip(cont.net_sharpe, cont.ci95_lo, cont.ci95_hi)]
    cont["round turns/yr"] = cont.round_turns_per_yr.round(0)
    cont["avg cost per round turn (USD)"] = cont.avg_cost_per_round_turn_usd.round(2)
    A(md(cont[["book", "run", "net Sharpe [95% CI]", "round turns/yr", "avg cost per round turn (USD)", "fund_10k_round_turn_usd"]]))
    A("")
    imp = ex[(ex.period == "2001-2017") & (ex.impact_coef == 0.5) & (ex.adv_variant == "primary_yahoo_adv")].copy()
    imp["net Sharpe [95% CI]"] = [ci(a, b, c) for a, b, c in zip(imp.net_sharpe, imp.ci95_lo, imp.ci95_hi)]
    imp["AUM"] = imp.aum.map("${:,.0f}".format)
    A("Square-root impact, coefficient 0.5, Yahoo ADV (upper bound on impact):")
    A("")
    A(md(imp[["book", "AUM", "net Sharpe [95% CI]"]]))
    A("")
    ct = cap.groupby(["book", "adv_variant", "impact_coef"])["capacity_aum_drop0p10"].first().reset_index()
    ct["capacity AUM (USD)"] = ct["capacity_aum_drop0p10"].map("{:,.0f}".format)
    A("Capacity = largest AUM on the grid with net Sharpe within 0.10 of the $10m value:")
    A("")
    A(md(ct[["book", "adv_variant", "impact_coef", "capacity AUM (USD)"]]))
    A("")
    A("Yahoo ADV is unreliable for GC/SI/HG/PL/PA; the two ADV variants bracket the truth. Figure: `results/v2/figures/capacity.png`.")
    A("")
    A("## E1 HMM style tilt (EXPLORATORY, never headline)")
    A("")
    A(f"Window {e1['window'][0]} to {e1['window'][1]} ({e1['n_months']} months). Base {ci(*e1['base_sharpe'])}, tilt {ci(*e1['tilt_sharpe'])}; "
      f"difference {ci(*e1['diff_tilt_minus_base'], p=3)}. The tilt did not help. {e1['note']}.")
    A("")
    A(f"## Seen period 2018-2026 - {SEEN}")
    A("")
    A("v1 already reported 2018-2026, so none of this is out-of-sample evidence. Lag 2. Impact rows use coefficient 0.5 at AUM $100m. "
      "The 2001-2017 rows are the same books and execution for comparison. Books: v1 blend, H1 blend, and the annual-equal allocation on the H1 smoother.")
    A("")
    s = sp.copy()
    s["net Sharpe [95% CI]"] = [ci(a, b, c) for a, b, c in zip(s.net_sharpe, s.ci95_lo, s.ci95_hi)]
    s["ann ret"] = s.ann_return.map("{:.3f}".format)
    s["max DD"] = s.max_drawdown.map("{:.3f}".format)
    s["impact cost/yr"] = s.ann_cost_impact.map("{:.4f}".format)
    s["rebalance days"] = s.n_rebalance_days
    s["days"] = s.n_days
    A(md(s[["period", "book", "execution", "net Sharpe [95% CI]", "ann ret", "max DD", "impact cost/yr", "rebalance days", "days"]]))
    A("")
    A("Tearsheets (equity, drawdown, rolling Sharpe, monthly table, Monte Carlo, costs, assumptions): `results/v2/tearsheets/*.html`. "
      f"Files with `seen_2018_2026` in the name are the {SEEN}.")
    A("")
    A("## Forward test")
    A("")
    if n_fwd == 0:
        A("**0 days tracked.** The forward period starts 2026-11-01 and the data on disk ends before it. First read: 2027-11 (12 months). "
          "Run `python scripts/v2/forward.py --refresh` daily; it appends only new dates to `results/v2/forward/forward.csv`. "
          "Books: v1_blend, h1_blend, alloc_annual_equal.")
    else:
        A(f"{n_fwd} days tracked. First read: 2027-11 (12 months). Do not read Sharpe before then.")
        A("")
        A(md(fwd.groupby("book")["net_return"].agg(["count", "mean", "std"]).reset_index()))
    A("")
    A("## ManifoldBT cross-check")
    A("")
    A("The qengine backtester was cross-checked against ManifoldBT 0.31.0 before its licence ended (parity diagnostics, not performance claims). "
      "Full tables and mismatches: [`qengine/PARITY.md`](../../qengine/PARITY.md); raw outputs for the P8 rules: [`results/v2/manifoldbt/`](../results/v2/manifoldbt/).")
    if pm and ps:
        A("")
        A(f"Engine parity (P7 trend weights): daily-return correlation with ManifoldBT {pm.group(1)} (run_weights), {pm.group(2)} (run_contracts); "
          f"Sharpe mbt {ps.group(1)}, run_weights {ps.group(2)}, run_contracts {ps.group(3)}.")
    A("")
    A("P8's two price-only styles were also written in the ManifoldBT DSL (`mom`: 12-1 return, cross-sectional tercile long/short; `rev`: short-term reversal) "
      "on 33 tickers, 2001-2017, synthetic bars built from P8 returns, one median fee, no slippage or roll cost. These are tool outputs, not claims; "
      "ManifoldBT annualises with sqrt(365.25), so its Sharpes are not comparable with the qengine sqrt(252) figures.")
    A("")
    rows = []
    for n_, nm in (("mom", "momentum DSL"), ("rev", "reversal DSL")):
        me, wf, la, mc = (J(f"{k}_{n_}.json", MB) for k in ("metrics", "walk_forward", "lookahead", "monte_carlo"))
        oos = [f["oos_metrics"]["sharpe"] for f in wf["folds"]]
        rows.append([nm, f"{me['sharpe']:.2f}", f"{me['max_drawdown']:.1%}", f"{np.mean(oos):.2f} ({', '.join(f'{x:.2f}' for x in oos)})",
                     "pass" if la["honest"]["passed"] else "FAIL", "caught" if not la["deliberate_lead1"]["passed"] else "MISSED",
                     f"{mc['prob_of_ruin']:.0%}"])
    A(md(pd.DataFrame(rows, columns=["rule", "Sharpe (full run)", "max DD", "walk-forward OOS Sharpe, mean (folds)",
                                     "look-ahead check", "deliberate lead(1)", "MC prob. of ruin"])))
    A("")
    A("Both DSL rules were weak: negative full-period Sharpe, deep drawdowns, and no consistent out-of-sample gain across folds. "
      "That agrees with the main P8 result that the price-only styles have no demonstrated edge after costs. "
      "The look-ahead checker passed the honest rules and caught the deliberate `.lead(1)` in both. "
      "Carry, value, macro and other styles need FRED data and were not run in ManifoldBT.")
    A("")
    A("## Limitations")
    A("")
